describe("extractMptIssuanceIds", () => {
  it.each([
    [
      "an MPT Payment",
      PAYMENT_MPT,
      "0631381B71048C4D35D2044917EE3C26F60E6CA8FC954A71",
    ],
    [
      "an MPT Payment with a memo",
      PAYMENT_MPT_WITH_MEMO,
      "000000050511E17DB83BB6F113939D67BC8EA539EDC926FC",
    ],
    [
      "an MPT Clawback",
      CLAWBACK_MPT,
      "064E278B6D15D1F5614B4D4E3183F835BCD62E7F6FD9FFD8",
    ],
    [
      "an MPTokenAuthorize",
      AUTHORIZE,
      "0631381B71048C4D35D2044917EE3C26F60E6CA8FC954A71",
    ],
    [
      "an MPTokenIssuanceSet",
      ISSUANCE_SET,
      "06250C1982A2A3C10B2AD7917E90F6538BD18553EAE55AEF",
    ],
    [
      "an MPTokenIssuanceDestroy",
      ISSUANCE_DESTROY,
      "0631381671048C4D35D2044917EE3C26F60E6CA8FC954A71",
    ],
  ])("should read the issuance id of %s", (_label, transaction, id) => {
    expect(extractMptIssuanceIds(transaction)).toEqual([id]);
  });

  it("should return the same issuance id once for Amount and SendMax", () => {
    const amount =
      "60 00000000000004D2 000000050511E17DB83BB6F113939D67BC8EA539EDC926FC";
    expect(extractMptIssuanceIds(tx(`120000 61${amount} 69${amount}`))).toEqual(
      ["000000050511E17DB83BB6F113939D67BC8EA539EDC926FC"],
    );
  });

  it.each([
    ["an XRP Payment", PAYMENT_XRP],
    ["an MPTokenIssuanceCreate", ISSUANCE_CREATE],
    ["an empty transaction", new Uint8Array()],
    ["a truncated MPT Payment", PAYMENT_MPT.slice(0, 40)],
  ])("should return no issuance id for %s", (_label, transaction) => {
    expect(extractMptIssuanceIds(transaction)).toEqual([]);
  });
});
